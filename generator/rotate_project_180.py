"""Rotate physical chip geometry and exported masks, not flow-chart positions.

The generator's internal routing remains canonical. Apply orientation only at
publication, so shape, split, timing, and channel identities are not regenerated.
"""
import argparse
import csv
from decimal import Decimal as D
import hashlib
import io
import json
from pathlib import Path
import re
import xml.etree.ElementTree as E

WIDTH, HEIGHT = 256, 192
BASE_CHIP = 'ChipArea_192_256_96_SIRO'
ROTATED_CHIP = BASE_CHIP + '_R180'
REPORT = '布局与电极180度旋转校验_20261022.json'
BOX = re.compile(r'\((\d+),(\d+)\)\((\d+),(\d+)\)')


def rotate_code(code):
    """RelayCode is (Y,X)(H,W); rectangle bounds are half-open."""
    if not code:
        return code
    def replace(m):
        y,x,h,w = map(int,m.groups())
        assert 0 <= x < x+w <= WIDTH and 0 <= y < y+h <= HEIGHT
        return f'({HEIGHT-y-h},{WIDTH-x-w})({h},{w})'
    result = BOX.sub(replace,code)
    assert not BOX.sub('',code).strip(';'), ('Unparsed RelayCode',code)
    return result


def rotate_script(text):
    root = E.fromstring(text)
    assert root.get('ChipsetType') == BASE_CHIP, 'Input must be canonical, not already rotated'
    text = re.sub(r'RelayCode="([^"]*)"',lambda m:'RelayCode="'+rotate_code(m[1])+'"',text)
    return text.replace(f'ChipsetType="{BASE_CHIP}"',f'ChipsetType="{ROTATED_CHIP}"')


def rotate_csv(data):
    """Retain row order: Tec, magnet, and well identities follow their geometry."""
    text = data.decode('utf-8-sig')
    reader = csv.DictReader(io.StringIO(text));headers = reader.fieldnames
    assert headers == ['Type','StartX','StartY','Width','Height']
    rows = list(reader)
    for row in rows:
        x,y,w,h = (D(row[k]) for k in headers[1:])
        assert 0 <= x < x+w <= WIDTH and 0 <= y < y+h <= HEIGHT
        row['StartX'] = format(D(WIDTH)-x-w,'f')
        row['StartY'] = format(D(HEIGHT)-y-h,'f')
    stream = io.StringIO(newline='')
    writer = csv.DictWriter(stream,headers,lineterminator='\r\n' if '\r\n' in text else '\n')
    writer.writeheader();writer.writerows(rows)
    return stream.getvalue().encode()


def verify_scripts(before,after):
    a,b = E.fromstring(before),E.fromstring(after)
    assert b.get('ChipsetType') == ROTATED_CHIP
    b.set('ChipsetType',BASE_CHIP)
    frames,rectangles = 0,0
    for source,target in zip(a.iter('RelayItem'),b.iter('RelayItem')):
        code = source.get('RelayCode','');rotated = target.get('RelayCode','')
        assert rotate_code(code) == rotated
        assert rotate_code(rotated) == code
        target.set('RelayCode',code)
        frames += 1;rectangles += len(BOX.findall(code))
    # Exact inverse comparison also checks node counts, every temperature and
    # control identity, loops, dependencies, durations, pulse, Amp, and Freq.
    assert E.tostring(a) == E.tostring(b), 'Non-coordinate parameters changed'
    return dict(frames=frames,rectangles=rectangles,all_non_coordinate_parameters_unchanged=True)


def verify_csv(before,after):
    a=list(csv.DictReader(io.StringIO(before.decode('utf-8-sig'))))
    b=list(csv.DictReader(io.StringIO(after.decode('utf-8-sig'))))
    assert len(a)==len(b)
    counts={};tec=[];magnet=[]
    for index,(source,target) in enumerate(zip(a,b),start=2):
        assert source['Type']==target['Type']
        typ=source['Type'];counts[typ]=counts.get(typ,0)+1
        x,y,w,h=(D(source[k]) for k in ('StartX','StartY','Width','Height'))
        xx,yy,ww,hh=(D(target[k]) for k in ('StartX','StartY','Width','Height'))
        assert (ww,hh)==(w,h) and (xx,yy)==(WIDTH-x-w,HEIGHT-y-h)
        if typ=='Tec':tec.append(dict(channel=f'Heater{len(tec)+1}',csv_line=index,
            before=[str(v) for v in (x,y,w,h)],after=[str(v) for v in (xx,yy,ww,hh)]))
        if typ=='Magnet':magnet.append(dict(csv_line=index,before=[str(x+w/2),str(y+h/2)],
                                           after=[str(xx+w/2),str(yy+h/2)]))
    assert len(tec)==6 and len(magnet)==96
    return dict(feature_counts=counts,tec_regions_row_identity_preserved=tec,
                magnet_centres=magnet,well_row_identity_preserved=True)


def publication_files(folder):
    folder=Path(folder);manifest=folder/'PTseq_SIRO16_A_10x.elabprj'
    # Other project names generated by build.py are accepted without guessing.
    if not manifest.exists():
        manifests=list(folder.glob('*.elabprj'));assert len(manifests)==1
        manifest=manifests[0]
    mt=manifest.read_text();assert E.fromstring(mt).get('ChipModel')==BASE_CHIP
    source=folder/(BASE_CHIP+'.csv')
    if not source.exists():source=Path(__file__).with_name(BASE_CHIP+'.csv')
    source_csv=source.read_bytes();rotated_csv=rotate_csv(source_csv)
    layout_audit=verify_csv(source_csv,rotated_csv)
    files={folder/(ROTATED_CHIP+'.csv'):rotated_csv}
    files[manifest]=mt.replace(f'ChipModel="{BASE_CHIP}"',f'ChipModel="{ROTATED_CHIP}"').encode()
    scripts=[]
    includes=['main']+[f.get('include') for f in E.fromstring(mt) if f.get('include')!='main']
    for stem in includes:
        path=folder/(stem+'.elab');text=path.read_text();rotated=rotate_script(text)
        scripts.append(dict(file=path.name,before_sha256=hashlib.sha256(text.encode()).hexdigest(),
            after_sha256=hashlib.sha256(rotated.encode()).hexdigest(),**verify_scripts(text,rotated)))
        files[path]=rotated.encode()
    # Explicit electrode coordinates in the operator table must not remain in
    # the old orientation. Labels E/F/S/B remain identity labels, not compass sides.
    for name in ('手工吸液顺序.csv','手工加液运行.html'):
        path=folder/name
        if not path.exists():continue
        raw=path.read_bytes().decode('utf-8-sig')
        updated=BOX.sub(lambda m:rotate_code(m[0]),raw)
        if name.endswith('.html'):
            note=('<p>当前工程：芯片布局及全部步骤电极已整体旋转180°（256×192）。'
                  'E/F/S/B与A1–A16保留原身份，位置随布局旋转；原顶部E孔现位于底部，'
                  '原底部F孔现位于顶部。温控区域顺序及Heater1指令身份保留，磁铁仍由外部控制。'
                  '实体温控接线与磁铁到位情况不属于本次静态校验。</p>')
            updated,n=re.subn(r'(</h1>)',lambda m:m[1]+note,updated,count=1);assert n==1
        files[path]=updated.encode()
    proof=dict(status='passed',date='2026-10-22',rotation_degrees=180,
        grid_width=WIDTH,grid_height=HEIGHT,source_chip=BASE_CHIP,published_chip=ROTATED_CHIP,
        scripts=scripts,layout=layout_audit,flowchart_positions_unchanged=True,
        transport_shape_area_split_merge_and_timing_unchanged=True,
        heater_commands='Heater1 retained; no inferred Heater1-to-Heater6 rewiring',
        active_tec_identity_unchanged=True,
        magnet_commands='External control; no addressable magnet/motor commands added or remapped',
        physical_heater_wiring_verified=False,physical_magnet_alignment_verified=False,
        first_water_run_tag='tft-first-on-chip-water-run-20261022',
        first_water_run_tag_target_unchanged=True,
        chip_csv_before_sha256=hashlib.sha256(source_csv).hexdigest(),
        chip_csv_after_sha256=hashlib.sha256(rotated_csv).hexdigest(),
        previous_geometry_reports_apply_to_pre_rotation_coordinates=True,
        GUI_checked=False,hardware_verified=False)
    files[folder/REPORT]=(json.dumps(proof,ensure_ascii=False,indent=2)+'\n').encode()
    return files,proof


def write_publication(folder):
    files,proof=publication_files(folder)
    for path,data in files.items():path.write_bytes(data)
    return proof


if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('folder',type=Path);ap.add_argument('--write',action='store_true')
    args=ap.parse_args();files,proof=publication_files(args.folder)
    if args.write:
        for path,data in files.items():path.write_bytes(data)
    print(json.dumps({k:proof[k] for k in ('status','rotation_degrees','published_chip','scripts')},ensure_ascii=False,indent=2))
